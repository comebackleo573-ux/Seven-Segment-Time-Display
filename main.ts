// Date string converters
function getDayOfWeek (day: number) {
    return [
    "Sunday",
    "Monday",
    "Tuesday",
    "Wednesday",
    "Thursday",
    "Friday",
    "Saturday"
    ][day]
}
function formatNumber (value: number) {
    return ("0" + value).substr(-2)
}
function getMonth (month: number) {
    return [
    "January",
    "February",
    "March",
    "April",
    "May",
    "June",
    "July",
    "August",
    "September",
    "October",
    "November",
    "December"
    ][month]
}
